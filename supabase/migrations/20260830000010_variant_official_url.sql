-- =============================================================================
-- 옵션별 공식몰 URL
--
-- 캐나다구스는 **색상마다 PDP 가 다르다** (로고 디스크까지 곱해진다).
-- 상품 단위 `products.official_url` 하나로는 나머지 색상 페이지를 가리킬 수 없다.
--
-- 브랜드마다 사정이 다르다:
--   아크테릭스·코치·폴로·룰루레몬  →  상품 페이지 하나. 색상은 그 안에서 고른다
--   캐나다구스                     →  색상마다 페이지가 따로
--
-- 그래서 **둘 다 둔다.** 상품 단위는 대표 진입점이고, 옵션 단위는 정확한 주소다.
-- 옵션에 값이 없으면 상품 값으로 떨어진다 — 그 판단은 읽는 쪽이 한다.
--
-- `supplier_listings.product_url` 과 겹쳐 보이지만 다르다. 저쪽은 재고 수집기가
-- 채우는 **감시 대상** 목록이라, 수집 전이거나 감시하지 않는 옵션에는 행이 없다.
-- 여기는 카탈로그가 채우는 사실이다.
-- =============================================================================

alter table product_variants
  add column official_url text
    check (official_url is null or official_url ~ '^https://');

comment on column product_variants.official_url is
  '이 옵션(색상)의 공식몰 페이지. 색상마다 PDP 가 다른 브랜드(캐나다구스)에서만 채워진다. '
  '없으면 products.official_url 로 떨어진다.';
