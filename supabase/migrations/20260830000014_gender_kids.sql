-- =============================================================================
-- 20260830000014 — 아동 라인 (캐나다구스 KIDS)
-- =============================================================================
--
-- 캐나다구스가 `KIDS(2~7years)` · `KIDS(6+years)` 두 라인을 낸다. 지금 `product_gender`는
-- men·women·unisex 뿐이라 담을 자리가 없다.
--
-- **`unisex`로 대신하지 않는다.** unisex 는 "남녀 목록 양쪽에 나온다"는 뜻으로 쓰고 있어서
-- (`filterGender`), 아동복을 거기 넣으면 남성 아우터 목록에 아동 파카가 섞인다.
-- 아동은 어느 쪽에도 나오면 안 되는 **별개의 축**이다.
--
-- 두 라인을 값 두 개로 쪼개지 않는다. 나이대 차이는 성별이 아니라 **사이즈 척도**의 차이이고,
-- 그건 `product_variants.size` 가 이미 담는다:
--   2~7years  2-3 · 4-5 · 6-7
--   6+years   XS (6) · S (7-8) · M (10-12) · L (14-16) · XL (18)
-- 상품 이름도 이미 `Kids ...` / `Youth ...` 로 갈려 있다.
--
-- **이 파일은 값만 추가하고 쓰지 않는다.** `alter type ... add value` 로 넣은 값을 같은
-- 트랜잭션에서 사용하면 Postgres 가 `unsafe use of new value` 로 거절한다 — Supabase SQL
-- 에디터도 `npm run db:check` 도 파일 하나를 한 트랜잭션으로 돌리므로, 여기서 'kids' 를
-- 참조하는 제약·뷰·시드를 같이 쓰면 마이그레이션이 통째로 실패한다.
-- =============================================================================

alter type product_gender add value if not exists 'kids';
